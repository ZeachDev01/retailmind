function send_brevo_email(string $email, string $subject, string $message, ?string $htmlContent = null): bool
{
    $config = get_store_brevo_settings(App\Core\Database::connection());
    $apiKey = trim((string)$config['brevo_api_key']);
    $from = trim((string)($config['brevo_sender_email'] ?? ''));
    if ($apiKey === '' || !filter_var($from, FILTER_VALIDATE_EMAIL)) {
        throw new RuntimeException('Configure a Brevo API key and verified sender address in Store Settings.');
    }

    $payloadData = [
        'sender' => [
            'email' => $from,
            'name' => brevo_sender_name($config),
        ],
        'to' => [['email' => $email]],
        'subject' => $subject,
        'textContent' => $message,
    ];
    if ($htmlContent !== null && trim($htmlContent) !== '') {
        $payloadData['htmlContent'] = $htmlContent;
    }

    $payload = json_encode($payloadData, JSON_UNESCAPED_SLASHES);
    if ($payload === false) {
        return false;
    }

    $caBundle = ini_get('curl.cainfo') ?: ini_get('openssl.cafile');
    if (!$caBundle) {
        $candidatePaths = [
            'C:\\xampp\\apache\\bin\\curl-ca-bundle.crt',
            'C:\\xampp\\phpMyAdmin\\vendor\\composer\\ca-bundle\\res\\cacert.pem',
        ];
        foreach ($candidatePaths as $candidate) {
            if (is_file($candidate)) {
                $caBundle = $candidate;
                break;
            }
        }
    }

    if (function_exists('curl_init')) {
        $curl = curl_init('https://api.brevo.com/v3/smtp/email');
        $curlOptions = [
            CURLOPT_POST => true,
            CURLOPT_POSTFIELDS => $payload,
            CURLOPT_HTTPHEADER => [
                'Accept: application/json',
                'Content-Type: application/json',
                'api-key: ' . $apiKey,
            ],
            CURLOPT_RETURNTRANSFER => true,
            CURLOPT_TIMEOUT => max(5, (int)env('MAIL_TIMEOUT', 30)),
        ];
        if ($caBundle && is_file($caBundle)) {
            $curlOptions[CURLOPT_CAINFO] = $caBundle;
        }
        curl_setopt_array($curl, $curlOptions);
        $response = curl_exec($curl);
        $httpCode = (int)curl_getinfo($curl, CURLINFO_HTTP_CODE);
        $curlError = curl_error($curl);
        if (function_exists('curl_close')) {
            @curl_close($curl);
        }

        if ($response === false || $curlError !== '' || $httpCode < 200 || $httpCode >= 300) {
            $detail = '';
            if (is_string($response) && $response !== '') {
                $json = json_decode($response, true);
                $detail = trim((string)($json['message'] ?? ''));
            }
            throw new RuntimeException($detail !== ''
                ? $detail
                : ($curlError !== '' ? $curlError : "Brevo API returned HTTP {$httpCode}."));
        }

        return true;
    }

    // Native HTTPS stream fallback when cURL extension is unavailable
    $contextOptions = [
        'http' => [
            'method' => 'POST',
            'header' => "Accept: application/json\r\nContent-Type: application/json\r\napi-key: " . $apiKey . "\r\n",
            'content' => $payload,
            'ignore_errors' => true,
            'timeout' => max(5, (int)env('MAIL_TIMEOUT', 30)),
        ],
    ];
    if ($caBundle && is_file($caBundle)) {
        $contextOptions['ssl'] = ['cafile' => $caBundle];
    }
    $context = stream_context_create($contextOptions);
    $response = @file_get_contents('https://api.brevo.com/v3/smtp/email', false, $context);
    $httpCode = 0;
    $responseHeaders = function_exists('http_get_last_response_headers')
        ? (http_get_last_response_headers() ?? [])
        : ($http_response_header ?? []);
    if (isset($responseHeaders[0]) && preg_match('#HTTP/\S+\s+(\d{3})#', $responseHeaders[0], $matches)) {
        $httpCode = (int)$matches[1];
    }
    if ($response === false || $httpCode < 200 || $httpCode >= 300) {
        $detail = '';
        if ($response !== false) {
            $json = json_decode($response, true);
            $detail = (string)($json['message'] ?? '');
        }
        throw new RuntimeException($detail !== '' ? $detail : "Brevo API returned HTTP {$httpCode}.");
    }

    return true;
}

function store_email_key(): string
{
    static $key = null;
    if ($key !== null) return $key;

    $path = App\Backup\RecoveryStore::path('store-email.key');
    if (!is_file($path)) {
        $handle = @fopen($path, 'x+b');
        if ($handle !== false) {
            $written = fwrite($handle, bin2hex(random_bytes(32)) . "\n");
            fflush($handle);
            if (function_exists('fsync')) fsync($handle);
            fclose($handle);
            if ($written !== 65) throw new RuntimeException('Email credential encryption is unavailable.');
            @chmod($path, 0600);
        }
    }
    $encoded = trim((string)@file_get_contents($path));
    if (!preg_match('/^[a-f0-9]{64}$/D', $encoded)) {
        throw new RuntimeException('Email credential encryption is unavailable.');
    }
    return $key = hex2bin($encoded);
}

function encrypt_store_email_secret(string $secret): string
{
    if (!extension_loaded('openssl')) throw new RuntimeException('OpenSSL is required to save Brevo credentials.');
    $iv = random_bytes(12);
    $tag = '';
    $ciphertext = openssl_encrypt($secret, 'aes-256-gcm', store_email_key(), OPENSSL_RAW_DATA, $iv, $tag);
    if ($ciphertext === false) throw new RuntimeException('Brevo credentials could not be encrypted.');
    return 'v1:' . base64_encode($iv . $tag . $ciphertext);
}

function decrypt_store_email_secret(string $encrypted): string
{
    if (!str_starts_with($encrypted, 'v1:') || !extension_loaded('openssl')) {
        throw new RuntimeException('Saved Brevo credentials cannot be read. Enter the API key again.');
    }
    $payload = base64_decode(substr($encrypted, 3), true);
    if ($payload === false || strlen($payload) < 29) {
        throw new RuntimeException('Saved Brevo credentials cannot be read. Enter the API key again.');
    }
    $secret = openssl_decrypt(substr($payload, 28), 'aes-256-gcm', store_email_key(), OPENSSL_RAW_DATA,
        substr($payload, 0, 12), substr($payload, 12, 16));
    if ($secret === false) throw new RuntimeException('Saved Brevo credentials cannot be read. Enter the API key again.');
    return $secret;
}

function get_store_brevo_settings(PDO $pdo): array
{
    $settings = get_store_settings($pdo);
    $encryptedKey = trim((string)($settings['brevo_api_key'] ?? ''));
    $settings['brevo_api_key_saved'] = $encryptedKey !== '';
    $settings['brevo_api_key'] = $settings['brevo_api_key_saved']
        ? decrypt_store_email_secret($encryptedKey)
        : '';
    return $settings;
}

/** Send all application email through the Brevo API. */
function send_email_notification(string $email, string $subject, string $message, ?string $htmlContent = null): bool
{
    if (!filter_var($email, FILTER_VALIDATE_EMAIL)) return false;
    $success = false;
    $provider = strtolower((string)env('MAIL_MAILER', '')) === 'disabled' ? 'disabled' : 'brevo-api';
    $errorMessage = null;
    if ($provider === 'disabled') {
        $errorMessage = 'Email delivery disabled by the current environment.';
    } else {
        try {
            $success = send_brevo_email($email, $subject, $message, $htmlContent);
        } catch (Throwable $exception) {
            $errorMessage = $exception->getMessage();
            error_log('Email delivery failed: ' . $errorMessage);
        }
    }

    try {
        $pdo = App\Core\Database::connection();
        if (!App\Database\Schema::tableExists($pdo, 'email_delivery_log')) $pdo->exec("CREATE TABLE IF NOT EXISTS email_delivery_log (
            email_log_id BIGINT AUTO_INCREMENT PRIMARY KEY,
            recipient VARCHAR(190) NOT NULL,
            subject VARCHAR(255) NOT NULL,
            status ENUM('sent','failed','queued') NOT NULL,
            provider VARCHAR(50) NULL,
            error_message TEXT NULL,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )");
        $stmt = $pdo->prepare('INSERT INTO email_delivery_log (recipient, subject, status, provider, error_message) VALUES (?, ?, ?, ?, ?)');
        $stmt->execute([$email, $subject, $success ? 'sent' : 'failed', $provider, $errorMessage]);
    } catch (Throwable $loggingError) {
        error_log('Could not write email delivery log: ' . $loggingError->getMessage());
    }
    return $success;
}

/**
 * Active admin and super admin users, resolved from both user_roles and the
 * primary users.role_id fallback. Used to deliver remote-access URL updates.
 */
function tunnel_notify_recipients(PDO $pdo): array
{
    try {
        $stmt = $pdo->query(
            "SELECT DISTINCT u.email
             FROM users u
             JOIN roles r ON r.role_name IN ('admin','super_admin')
             WHERE u.status = 'active'
               AND u.email IS NOT NULL AND u.email <> ''
               AND (
                   EXISTS (SELECT 1 FROM user_roles ur WHERE ur.user_id = u.user_id AND ur.role_id = r.role_id)
                   OR (u.role_id = r.role_id AND NOT EXISTS (SELECT 1 FROM user_roles ur2 WHERE ur2.user_id = u.user_id))
               )"
        );
        $recipients = [];
        while (($row = $stmt->fetch(PDO::FETCH_ASSOC)) !== false) {
            $email = trim((string)($row['email'] ?? ''));
            if ($email !== '' && filter_var($email, FILTER_VALIDATE_EMAIL)) {
                $recipients[$email] = true;
            }
        }
        return array_keys($recipients);
    } catch (Throwable $exception) {
        error_log('Remote access notify: could not resolve recipients: ' . $exception->getMessage());
        return [];
    }
}

/**
 * Email active admin and super admin users when the remote-access tunnel URL
 * changes (a quick-tunnel domain is rotated on restart). Dedupes against the
 * last notified URL so restarts do not re-email the same address.
 */
function notify_tunnel_url_change(PDO $pdo, string $newUrl): bool
{
    $newUrl = rtrim(trim($newUrl), '/');
    if ($newUrl === '' || !preg_match('#^https?://#i', $newUrl)) {
        return false;
    }

    $settings = get_store_settings($pdo);
    // Enabled by default; a Super Admin can switch it off explicitly.
    if (($settings['tunnel_url_notify_enabled'] ?? '1') === '0') {
        return false;
    }
    $lastNotified = trim((string)($settings['tunnel_last_notified_url'] ?? ''));
    if ($lastNotified === $newUrl) {
        return false;
    }

    $recipients = tunnel_notify_recipients($pdo);
    if (empty($recipients)) {
        return false;
    }

    // Record before sending so a failed send does not loop on every status poll.
    save_key_value_settings($pdo, 'store_settings', ['tunnel_last_notified_url' => $newUrl], null);

    $storeName = trim((string)($settings['store_name'] ?? 'RetailMind'));
    $sent = false;
    foreach ($recipients as $recipient) {
        if (send_email_notification(
            $recipient,
            $storeName . ' remote access URL updated',
            "The remote access URL has changed.\n\nNew URL: " . $newUrl . "\n\nUse this address to keep monitoring the system and store operations remotely."
        )) {
            $sent = true;
        }
    }
    return $sent;
}

function validate_calendar_date(mixed $rawDate): ?string
{
    if ($rawDate === null) {
        return null;
    }
    if (!is_string($rawDate) && !is_int($rawDate)) {
        throw new RuntimeException('Enter a valid expiration date.');
    }
    $trimmed = trim((string)$rawDate);
    if ($trimmed === '') {
        return null;
    }
    if (!preg_match('/^\d{4}-\d{2}-\d{2}$/D', $trimmed)) {
        throw new RuntimeException('Enter a valid expiration date.');
    }
    $date = DateTimeImmutable::createFromFormat('!Y-m-d', $trimmed);
    if (!$date || $date->format('Y-m-d') !== $trimmed || $trimmed < '1000-01-01') {
        throw new RuntimeException('Enter a valid expiration date.');
    }
    return $trimmed;
}
