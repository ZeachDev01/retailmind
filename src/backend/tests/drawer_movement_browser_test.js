const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const { execFileSync } = require('node:child_process');
const { chromium } = require('playwright');
(async () => {
    const browser = await chromium.launch({ headless: true });
    try {
        const page = await browser.newPage();
        const root = path.resolve(__dirname, '../../..');
        const html = execFileSync(process.env.PHP_BINARY || 'php', [path.join(__dirname, 'support/drawer_movement_fixture.php')], { encoding: 'utf8' });
        await page.route('http://drawer.test/**', route => {
            const asset = new URL(route.request().url()).pathname.match(/^\/assets\/(.*)/);
            return asset ? route.fulfill({path:path.join(root,'src/frontend/assets',asset[1])}) : route.fulfill({contentType:'text/html',body:html});
        });
        await page.goto('http://drawer.test/');
        await page.addStyleTag({ content: fs.readFileSync(path.join(root, 'src/frontend/assets/css/cashier-pages.css'), 'utf8') });
        assert.deepEqual(await page.locator('.shift-money-flow dt').allTextContents(), ['Starting cash', '+ Money in', '− Money out', '= Expected drawer']);
        assert.deepEqual(await page.locator('.shift-flow-total').allTextContents(), ['₱50.00', '₱150.00', '₱50.00', '₱150.00']);
        await page.getByRole('tab', {name:'Current movements',exact:true}).click();
        assert.equal(await page.locator('#current-shift-movements').isVisible(), true);
        assert.deepEqual(await page.locator('.shift-movement-table td[data-label="Amount"]').allTextContents(), ['+₱100.00', '−₱50.00']);
        assert.match(await page.locator('#current-shift-movements').innerText(), /From: Owner <cash box>/);
        assert.equal(await page.getByRole('link', {name:'All drawer movements'}).getAttribute('href'), '/components/cashier/history.php?type=movements');
        await page.getByRole('tab', {name:'Record movement',exact:true}).click();
        assert.equal(await page.locator('#movement-source').evaluate(el => el.required), true);
        assert.equal(await page.locator('#movement-source-label').innerText(), 'Cash from');
        await page.locator('#movement-type').selectOption('cash_out');
        assert.equal(await page.locator('#movement-source-label').innerText(), 'Cash to');
        assert.equal(await page.locator('#movement-reason').inputValue(), 'petty_cash');
        await page.locator('#movement-reason').selectOption('supplier_payment');
        await page.locator('#movement-amount').fill('10.25');
        assert.equal(await page.locator('#movement-type').evaluate(el => el.form.checkValidity()), false, 'Missing destination blocks submission');
        await page.locator('#movement-source').fill('Supplier');
        await page.locator('#movement-type').evaluate(el => el.form.addEventListener('submit', event => event.preventDefault()));
        await page.getByRole('button', {name:'Record movement', exact:true}).click();
        assert.equal(await page.getByRole('dialog', {name:'Authorize drawer movement'}).isVisible(), true);
        await page.locator('#movement-approver').fill('owner');
        await page.locator('#movement-approval-password').fill('fixture-password');
        const fields = await page.locator('#movement-type').evaluate(el => Object.fromEntries(new FormData(el.form)));
        assert.deepEqual(fields, { csrf_token:'fixture-csrf', action:'movement', movement_token:'fixture-movement', movement_type:'cash_out', amount:'10.25', reason:'supplier_payment', source_destination:'Supplier', note:'', approver_username:'owner', approver_password:'fixture-password' });
        await page.getByRole('button', {name:'Cancel', exact:true}).click();
        const otherIndex = await page.locator('#movement-reason').evaluate(el => [...el.options].findIndex(option => option.value === 'other' && !option.disabled));
        await page.locator('#movement-reason').selectOption({ index: otherIndex });
        assert.equal(await page.locator('#movement-note').evaluate(el => el.required), true);
        assert.equal(await page.locator('#movement-approver').evaluate(el => el.disabled), true);
        await page.locator('#movement-type').selectOption('safe_drop');
        assert.equal(await page.locator('#movement-reason').inputValue(), 'excess_cash');
        assert.equal(await page.locator('#movement-note').evaluate(el => el.required), false);
        const refundPage = await browser.newPage();
        const refundHtml = execFileSync(process.env.PHP_BINARY || 'php', [path.join(__dirname, 'support/drawer_movement_fixture.php'), '--refund'], {encoding:'utf8'});
        await refundPage.setContent(refundHtml);
        assert.deepEqual(await refundPage.locator('.shift-flow-total').allTextContents(), ['₱0.00', '₱171.00', '₱60.00', '₱111.00']);
        const flow = await refundPage.locator('.shift-money-flow').innerText();
        assert.match(flow, /Cash sales\s+₱71.00/);
        assert.match(flow, /Drawer cash in\s+₱100.00/);
        assert.match(flow, /Cash refunds\s+₱60.00/);
        assert.doesNotMatch(flow, /25.00/, 'E-wallet refund is not shown as a drawer deduction');
        assert.deepEqual(await refundPage.locator('.shift-activity-counts dd').allTextContents(), ['1','2','1'], 'Sales, all-method refunds, and drawer movements are counted separately');
        const emptyHtml = execFileSync(process.env.PHP_BINARY || 'php', [path.join(__dirname, 'support/drawer_movement_fixture.php'), '--empty'], {encoding:'utf8'});
        await refundPage.setContent(emptyHtml);
        assert.deepEqual(await refundPage.locator('.shift-flow-total').allTextContents(), ['₱0.00','₱0.00','₱0.00','₱0.00']);
        assert.deepEqual(await refundPage.locator('.shift-activity-counts dd').allTextContents(), ['0','0','0'], 'Empty shift has zero activity counts');
        await refundPage.close();
        console.log('Drawer movement browser: passed (reasons, authorization fields and bound form)');
    } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
